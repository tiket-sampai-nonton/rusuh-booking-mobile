/**
 * PaymentRepository — domain PORT (ARCHITECTURE §2.1, §3, §4.4, §13 P5).
 *
 * Pure TS: no React / RN / Expo / browser / native / codegen imports.
 * Infrastructure implements this port; the composition root binds mock (dev
 * default) or the real adapter (mock-first, D10.5).
 *
 * RBT-010: refined to the Payment-service contract. The FE NEVER collects a
 * payment instrument (SNAP owns it) — it only creates an attempt and reads the
 * authoritative status; the BE returns a SNAP `redirectUrl`.
 */

/** Payment-attempt lifecycle (contract enum). */
export type PaymentStatus =
  | "READY"
  | "AWAITING_PAYMENT"
  | "PAID"
  | "FAILED"
  | "EXPIRED";

/** Allowed method buckets (contract enum) — no credit card. */
export type PaymentMethod =
  | "VA_BCA"
  | "VA_BNI"
  | "VA_BRI"
  | "VA_PERMATA"
  | "QRIS"
  | "GOPAY";

/** The outcome a SNAP callback reports (RBT-065). UNKNOWN keeps the attempt
 * non-terminal so the result gate keeps verifying (D10.4). */
export type SnapOutcome = "PAID" | "FAILED" | "UNKNOWN";

/** A payment attempt + the SNAP handoff URL the BE returns. */
export interface PaymentAttempt {
  readonly attemptId: string;
  readonly bookingId: string;
  readonly status: PaymentStatus;
  /** SNAP redirect URL (web) / WebView URL (mobile). Absent until created. */
  readonly redirectUrl?: string;
  /** Server-authoritative payment deadline (ISO-8601). */
  readonly paymentExpiresAt?: string;
  readonly serverTime?: string;
  /** Where SNAP returns on success / failure (contract return URLs, RBT-065). */
  readonly successReturnUrl?: string;
  readonly failedReturnUrl?: string;
}

/**
 * The payment page the BE serves for a booking (contract `PaymentPage`, RBT-060
 * AC1). The FE renders the order summary (total == `amountMinor`, with NO
 * service/hidden-fee line — D10.1), the SERVER-driven method list, and a
 * server-authoritative countdown from `paymentExpiresAt`/`serverTime`.
 */
export interface PaymentPage {
  readonly bookingId: string;
  /** Server-allowed methods for this booking (order = display order). */
  readonly methods: readonly PaymentMethod[];
  /** Order total in minor IDR — the ONLY amount shown (no fees added). */
  readonly amountMinor: number;
  readonly paymentExpiresAt: string;
  readonly serverTime: string;
  /** The in-flight attempt, if one exists (refresh-safe restore — RBT-061). */
  readonly currentAttempt?: PaymentAttempt;
}

/**
 * A one-time page token + the WebView URL it unlocks (contract `PageToken`,
 * RBT-062). The mobile app opens `pageUrl` in a WebView, then exchanges
 * `pageToken` for an `rb_pay` session cookie so the SAME FE payment page is
 * reused inside the WebView (D10.3). FE-NEED (O2): endpoints proposed, mocked.
 */
export interface PageToken {
  readonly pageToken: string;
  readonly pageUrl: string;
}

export interface PaymentRepository {
  /**
   * Fetch the payment page for a booking (`GET /payments/{bookingId}/page`,
   * RBT-060). Returns the server-authoritative summary + method list + deadline.
   */
  getPaymentPage(bookingId: string): Promise<PaymentPage>;
  /**
   * Mint a one-time page token + WebView URL (`POST /payments/{id}/page-tokens`,
   * RBT-062, FE-NEED O2). The mobile WebView loads `pageUrl`.
   */
  createPageToken(bookingId: string): Promise<PageToken>;
  /**
   * Exchange a page token for the `rb_pay` session cookie
   * (`POST /payment-page-sessions {pageToken}`, RBT-062, FE-NEED O2) so the FE
   * payment page is reused inside the WebView. Throws on an invalid/expired
   * token (PAYMENT_PAGE_TOKEN_INVALID).
   */
  exchangePageToken(pageToken: string): Promise<void>;
  /**
   * Create a payment attempt for a booking.
   * @param idempotencyKey minted in the use case/domain, reused on retry
   *   (ARCHITECTURE §4.3) — never generated by the transport/adapter.
   */
  createAttempt(
    bookingId: string,
    method: PaymentMethod,
    idempotencyKey: string,
  ): Promise<PaymentAttempt>;
  /** Verify the authoritative payment status for an attempt. */
  getStatus(attemptId: string): Promise<PaymentAttempt>;
  /**
   * The SNAP callback the gateway (or the local simulator, RBT-065) invokes when
   * the hosted page settles: the BE webhook sets the authoritative status, then
   * the FE re-verifies with `getStatus` — it NEVER trusts this callback alone
   * (D10.2/D10.4). Returns the resulting attempt. On the real adapter this POSTs
   * the callback endpoint; the mock flips the attempt (PAID/FAILED) or leaves it
   * non-terminal (UNKNOWN) so the result gate keeps polling.
   */
  snapCallback(attemptId: string, outcome: SnapOutcome): Promise<PaymentAttempt>;
}
